  String translate(String key) {
    final String languageCode = LocalizationService.instance.currentLanguage;
    String v = _localizedValues[languageCode]?[key] ?? '';
    if (v.isEmpty) v = key;
    // Prettify keys that look like snake_case or fallback keys
    if (v.contains('_')) {
      v = v.replaceAll('_', ' ');
      if (v.isNotEmpty) {
        v = v[0].toUpperCase() + v.substring(1);
      }
    }
    return v;
  }

  /// The wording for a business that is not a depot, when the key has one; otherwise the usual text.
  String translateForKind(String key, {required bool isDepot}) {
    if (!isDepot) {
      final String languageCode = LocalizationService.instance.currentLanguage;
      final String? other = _localizedValues[languageCode]?['${key}__non_depot'];
      if (other != null && other.isNotEmpty) return other;
    }
    return translate(key);
  }
