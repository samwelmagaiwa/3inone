// ignore_for_file: prefer_constructors_over_static_methods
class LocalizationService extends ChangeNotifier {
  LocalizationService._internal();
  static const String _languageKey = 'selected_language';

  Locale _currentLocale = const Locale('sw', 'TZ'); // Default to Swahili

  Locale get currentLocale => _currentLocale;
  String get currentLanguage => _currentLocale.languageCode;
  bool get isSwahili => _currentLocale.languageCode == 'sw';
  bool get isEnglish => _currentLocale.languageCode == 'en';

  static LocalizationService? _instance;

  static LocalizationService get instance {
    _instance ??= LocalizationService._internal();
    return _instance!;
  }

  Future<void> initialize() async {
    final SharedPreferences prefs = await SharedPreferences.getInstance();
    final String? savedLanguage = prefs.getString(_languageKey);

    if (savedLanguage != null) {
      _currentLocale = _getLocaleFromLanguageCode(savedLanguage);
    }

    notifyListeners();
  }

  Future<void> changeLanguage(String languageCode) async {
    final SharedPreferences prefs = await SharedPreferences.getInstance();
    await prefs.setString(_languageKey, languageCode);

    _currentLocale = _getLocaleFromLanguageCode(languageCode);
    notifyListeners();
  }

  Locale _getLocaleFromLanguageCode(String languageCode) {
    switch (languageCode) {
      case 'en':
        return const Locale('en', 'US');
      case 'sw':
      default:
        return const Locale('sw', 'TZ');
    }
  }

  String translate(String key) {
    return AppLocalizations.instance.translate(key);
  }

  /// [translate] for a text with blanks in it: "Details of {0}" with `['Jane']` reads "Details of Jane". Each `{n}`
  /// becomes the n-th argument. The words around the blanks belong to the translation, so each language puts the
  /// name (or amount, or error) where it belongs in its own sentence.
  String translateWith(String key, List<Object?> args) {
    String text = translate(key);
    for (int i = 0; i < args.length; i++) {
      // An error handed over as a blank is shown as plain words: no "Exception: ..." wrapper.
      final Object? arg = args[i];
      text = text.replaceAll('{$i}', arg != null && (arg is Exception || arg is Error) ? readableErrorMessage(arg) : '$arg');
    }
    return text;
  }

  /// [translate], but a business that is not a depot gets its own wording where a key has one
  /// (`<key>__non_depot`): "Depot details" becomes "Business details" for a shop. Depots, and keys with no
  /// other wording, read exactly as before.
  String translateForKind(String key, {required bool isDepot}) =>
      AppLocalizations.instance.translateForKind(key, isDepot: isDepot);

  /// The vehicle type the server stores ("bajaji", "pikipiki", "gari") as the name a person reads in the chosen
  /// language. A type this app does not know is shown as it came; no type reads "N/A".
  String vehicleTypeLabel(String? stored) {
    final String type = (stored ?? '').trim();
    if (type.isEmpty) {
      return translate('not_available_short');
    }
    switch (type.toLowerCase()) {
      case 'bajaji':
        return translate('vehicle_type_bajaji');
      case 'pikipiki':
        return translate('vehicle_type_pikipiki');
      case 'gari':
        return translate('vehicle_type_gari');
      default:
        return type;
    }
  }
}

