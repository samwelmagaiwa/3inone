  /// One section of the joined card: an optional icon + title, then its fields. Sections are told apart by
  /// [_sectionDivider], not by gaps or boxes of their own.
  Widget _section({required String id, String? title, IconData? icon, required List<Widget> children}) {
    return Padding(
      key: ValueKey<String>('product_section_$id'),
      padding: EdgeInsets.symmetric(horizontal: 10.w, vertical: 12.h),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: <Widget>[
          if (title != null) ...<Widget>[
            Row(
              children: <Widget>[
                if (icon != null) ...<Widget>[
                  Icon(icon, color: Colors.white70, size: 18.sp),
                  SizedBox(width: 8.w),
                ],
                Expanded(
                  child: Text(
                    title,
                    maxLines: 1,
                    overflow: TextOverflow.ellipsis,
                    style: ThemeConstants.headingStyle.copyWith(fontSize: 15.sp),
                  ),
                ),
              ],
            ),
            SizedBox(height: 10.h),
          ],
          ...children,
        ],
      ),
    );
  }

  /// The full-width hairline between two sections (the same line Settings draws between its rows).
  Widget _sectionDivider(String above) => Divider(
        key: ValueKey<String>('product_section_divider_$above'),
        color: Colors.white24,
        height: 1,
        thickness: 1,
      );

  /// The unit, price and stock fields. A depot's are exactly what they always were; the others quote prices
  /// per the unit they think in (a piece, a kg, a litre) and count stock in whole base units.
  List<Widget> _unitPriceStock(LocalizationService loc, InvCapabilities caps) {
    final bool sw = loc.isSwahili;
    final bool creating = widget.product == null;
    final bool weighed = !caps.isDepot && _measure != ProductMeasure.count;
    final bool hideStock = creating && _hasVariants; // each size / colour carries its own

    // ---- the unit row
    final Widget unitRow;
    if (caps.isDepot) {
      final List<String> unitOptions = ['pcs', 'crate', 'carton', 'katoni', 'pack', 'box', 'tray', 'dozen', 'sack', 'kg', 'litre'];
      if (!unitOptions.contains(_unit)) {
        unitOptions.add(_unit);
      }
      unitRow = _twoCol(
        leftFlex: 2,
        // Aligned along the bottom, as this row always was.
        align: CrossAxisAlignment.end,
        left: _dropdown(loc.translate('unit'), _unit, unitOptions, (v) {
          setState(() {
            _unitTouched = true;
            _unit = v!;
          });
        }),
        right: _input(
          loc.translate('unit_quantity'),
          _unitFactor,
          keyboard: TextInputType.number,
          hint: 'e.g. 1',
        ),
      );
    } else if (weighed) {
      unitRow = const SizedBox.shrink();
    } else {
      final List<String> unitOptions = ['pcs', 'pack', 'box', 'dozen', 'bottle', 'tray', 'sack', 'carton', 'katoni', 'crate'];
      if (!unitOptions.contains(_unit)) {
        unitOptions.add(_unit);
      }
      unitRow = _dropdown(sw ? 'Kipimo cha stoo' : 'Counted in', _unit, unitOptions, (v) {
        setState(() {
          _unitTouched = true;
          _unit = v!;
        });
      });
    }

    // ---- prices
    final int factor = caps.isDepot ? (_int(_unitFactor.text) < 1 ? 1 : _int(_unitFactor.text)) : 1;
    final String per = weighed ? _measure.bigUnit : _unit;
    final String unitLabel = (caps.isDepot ? _unit : per).trim().toUpperCase();
    final double costVal = parseAmount(_cost.text);
    final double priceVal = parseAmount(_price.text);
    final double profitPerUnit = priceVal - costVal;
    final String tier = caps.isDepot ? (_isWholesale ? 'wholesale' : 'retail') : (caps.saleTier == 'wholesale' ? 'wholesale' : 'retail');
    final String costLabel = caps.isDepot
        ? '${loc.translate('cost_price_per').replaceFirst(RegExp(r'1$'), '$factor')} $unitLabel)'
        : '${sw ? 'Bei ya kununua' : 'Cost price'} (${sw ? 'kwa' : 'per'} $unitLabel)';
    final String priceLabel = caps.isDepot
        ? '${loc.translate('selling_price_per').replaceFirst(RegExp(r'1$'), '$factor')} $unitLabel)'
        : '${tier == 'wholesale' ? (sw ? 'Bei ya jumla' : 'Wholesale price') : (sw ? 'Bei ya kuuza' : 'Selling price')} (${sw ? 'kwa' : 'per'} $unitLabel)';
    final String otherLabel = tier == 'wholesale'
        ? '${sw ? 'Bei ya rejareja' : 'Retail price'} (${sw ? 'si lazima' : 'optional'})'
        : '${sw ? 'Bei ya jumla' : 'Wholesale price'} (${sw ? 'si lazima' : 'optional'})';

    return <Widget>[
      if (!caps.isDepot) ...[
        MeasureChips(
          value: _measure,
          sw: sw,
          enabled: creating,
          onChanged: (ProductMeasure m) => setState(() {
            _measure = m;
            _stockUnitFactor = 1;
            if (m == ProductMeasure.count && (_unit == 'g' || _unit == 'ml')) _unit = 'pcs';
            if (m != ProductMeasure.count) _hasVariants = false;
          }),
        ),
        SizedBox(height: 8.h),
      ],
      unitRow,
      SizedBox(height: 8.h),
      _twoCol(
        left: _input(costLabel, _cost,
            keyboard: TextInputType.number, inputFormatters: [ThousandsFormatter()], hint: 'e.g. 20,000'),
        right: _input(priceLabel, _price,
            keyboard: TextInputType.number, inputFormatters: [ThousandsFormatter()], hint: 'e.g. 25,000'),
      ),
      Padding(
        padding: EdgeInsets.symmetric(vertical: 4.h, horizontal: 2.w),
        child: Text(
          '💡 ${loc.translate('profit_hint')}  (${formatAmount(priceVal)} − ${formatAmount(costVal)} = TZS ${formatAmount(profitPerUnit)} / ${caps.isDepot ? '$factor $_unit' : per})',
          style: ThemeConstants.captionStyle.copyWith(
            color: Colors.greenAccent.shade400,
            fontSize: 11.sp,
          ),
        ),
      ),
      // The same unit at the other level: a business that sells at both can give both prices.
      if (!caps.isDepot && caps.offersWholesalePrice && creating) ...[
        SizedBox(height: 4.h),
        _input(otherLabel, _otherPrice,
            keyboard: TextInputType.number, inputFormatters: [ThousandsFormatter()], hint: 'e.g. 22,000'),
      ],
      if (!hideStock) ...[
        SizedBox(height: 8.h),
        _twoCol(
          left: _input(
            '${loc.translate('quantity_in_stock')} (${weighed ? (_stockUnitFactor == 1 ? _measure.baseUnit : _measure.bigUnit) : _unit})',
            _qty,
            keyboard: TextInputType.number,
            hint: 'e.g. 100',
            inputFormatters: [FilteringTextInputFormatter.digitsOnly],
          ),
          right: _input(loc.translate('stock_alert_threshold'), _minStock,
              keyboard: TextInputType.number, hint: 'e.g. 24', inputFormatters: [FilteringTextInputFormatter.digitsOnly]),
        ),
        // Weighed goods: type the stock in kg or in grams -- whole numbers either way.
