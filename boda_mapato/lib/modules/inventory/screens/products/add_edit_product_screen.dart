  Future<void> _onSave() async {
    final LocalizationService loc = LocalizationService.instance;
    final bool sw = loc.isSwahili;

    if (_name.text.trim().isEmpty || _sku.text.trim().isEmpty) {
      ThemeConstants.showWarningSnackBar(
          context, loc.translate('field_required'));
      return;
    }

    final InventoryProvider inv = context.read<InventoryProvider>();
    final InvCapabilities caps = inv.capabilities;
    final bool creating = widget.product == null;
    final bool withVariants = _hasVariants && !_isService && !caps.isDepot && _measure == ProductMeasure.count;

    // A service: how long it takes and when to bring the client back must be sensible numbers (or empty).
    final int? duration = int.tryParse(_duration.text.trim());
    final int? rebookWeeks = int.tryParse(_rebook.text.trim());
    final double? commission = !_commissionOn ? null : double.tryParse(_commission.text.trim().replaceAll(',', '.'));
    final double? commissionFixed = !_commissionOn || _commissionFixed.text.trim().isEmpty ? null : parseAmount(_commissionFixed.text);
    // A package says which service it is for and how many visits (at least two) it holds.
    final int? packageSessions = int.tryParse(_packageSessions.text.trim());
    final int? packageDays = int.tryParse(_packageDays.text.trim());
    if (_isService && _isPackage && (_packageServiceId == null || packageSessions == null || packageSessions < 2)) {
      ThemeConstants.showErrorSnackBar(context, sw ? 'Kifurushi kinahitaji huduma na ziara 2 au zaidi.' : 'A package needs a service and 2 or more visits.');
      return;
    }
    List<PriceOption> options = const <PriceOption>[];
    if (_isService) {
      final List<PriceOption>? read = _readOptions(sw);
      if (read == null) return;
      options = read;
    }
    if (_isService) {
      if (commission != null && (commission < 0 || commission > 100)) {
        setState(() => _saveError = sw ? 'Kamisheni iwe kati ya 0 na 100.' : 'The commission must be between 0 and 100 percent.');
        return;
      }
      if (duration != null && (duration < 1 || duration > 1440)) {
        setState(() => _saveError = sw ? 'Muda uwe kati ya dakika 1 na 1440.' : 'The duration must be between 1 and 1440 minutes.');
        return;
      }
      if (rebookWeeks != null && (rebookWeeks < 1 || rebookWeeks > 52)) {
        setState(() => _saveError = sw ? 'Wiki za kumkumbusha mteja ziwe kati ya 1 na 52.' : 'The weeks to remind the client must be between 1 and 52.');
        return;
      }
    }

    // Selling units: a row with only half filled in is a mistake worth saying, not silently dropping.
    final List<UnitInput> units = <UnitInput>[];
    for (final UnitDraft d in _unitDrafts) {
      if (d.isEmpty && wholeNumber(d.factor.text) == 0) continue; // an untouched row
      final UnitInput? u = d.toInput();
      if (u == null) {
        setState(() => _saveError = sw ? 'Kila njia ya kuuza inahitaji jina na idadi (mfano katoni = 24).' : 'Each selling unit needs a name and how many it holds (e.g. carton = 24).');
        return;
      }
      units.add(u);
    }

    final List<VariantInput> variants = <VariantInput>[];
    if (withVariants) {
      for (final VariantDraft d in _variantDrafts) {
        final bool untouched = d.label.text.trim().isEmpty && d.qty.text.trim().isEmpty && d.price.text.trim().isEmpty;
        if (untouched) continue;
        final VariantInput? v = d.toInput();
        if (v == null) {
          setState(() => _saveError = sw ? 'Kila saizi/rangi inahitaji jina.' : 'Each size or colour needs a name.');
          return;
        }
        variants.add(v);
      }
      if (creating && variants.isEmpty) {
        setState(() => _saveError = sw ? 'Ongeza angalau saizi au rangi moja.' : 'Add at least one size or colour.');
        return;
      }
    }

    // The VAT rate: empty = the business default; a number (0 = exempt) is the product's own.
    final String vatText = _vat.text.trim();
    final double? vat = vatText.isEmpty ? null : double.tryParse(vatText.replaceAll(',', '.'));
    if (vatText.isNotEmpty && (vat == null || vat < 0 || vat > 100)) {
      setState(() => _saveError = sw ? 'VAT lazima iwe kati ya 0 na 100.' : 'VAT must be between 0 and 100.');
      return;
    }

    final ProductRequest req = buildProductRequest(
      caps: caps,
      // A depot does not work in kg / litres (the page shows plain units), so its goods are never converted.
      measure: caps.isDepot ? ProductMeasure.count : _measure,
      depotWholesaleMode: _isWholesale,
      unit: _unit,
      unitFactor: _int(_unitFactor.text),
      cost: _isService ? 0 : parseAmount(_cost.text),
      price: parseAmount(_price.text),
      otherPrice: _isService ? null : optionalAmount(_otherPrice.text),
      quantity: _isService ? 0 : _int(_qty.text),
      minStock: _isService ? 0 : _int(_minStock.text),
      stockUnitFactor: _stockUnitFactor,
      // A depot's selling units only count in retail mode (that is where it showed them).
      extraUnits: (caps.isDepot && _isWholesale) || _isService ? const <UnitInput>[] : units,
      variants: variants,
    );

    setState(() {
      _saving = true;
      _saveError = null;
    });
    final String? description =
        _description.text.trim().isEmpty ? null : _description.text.trim();
    final String? category =
        _category.text.trim().isEmpty ? null : _category.text.trim();
    final String? barcode =
        _barcode.text.trim().isEmpty ? null : _barcode.text.trim();

    bool ok;
    if (!creating) {
      final InvProduct existing = widget.product!;
      ok = await inv.updateProduct(
        id: existing.id,
        name: _name.text.trim(),
        description: description,
        costPrice: req.costPrice,
        sellingPrice: req.sellingPrice,
        quantity: req.quantity,
        minStock: req.minStock,
        category: category,
        categoryId: _categoryId,
        brandId: _brandId,
        unit: caps.isDepot ? _unit : req.unit,
        unitFactor: caps.isDepot ? req.unitFactor : null,
        status: _active ? 'active' : 'inactive',
        barcode: barcode,
        priceTier: req.priceTier,
        taxPercent: vat,
        clearTax: vat == null && existing.taxPercent != null,
        variantLabel: existing.isVariant && _variantLabel.text.trim() != (existing.variantLabel ?? '') ? _variantLabel.text.trim() : null,
        isService: _isService,
        durationMinutes: duration,
        rebookAfterWeeks: rebookWeeks,
        commissionPercent: _isService ? commission : null,
        commissionFixed: _isService ? commissionFixed : null,
        packageSessions: _isService && _isPackage ? packageSessions : null,
        packageServiceId: _isService && _isPackage ? _packageServiceId : null,
        packageValidDays: _isService && _isPackage ? packageDays : null,
        staffIds: _isService ? _staffIds.toList() : null,
        priceOptions: _isService ? options : null,
      );
      if (ok) {
        await _saveOtherPrices(inv, existing, caps, req);
        if (withVariants && variants.isNotEmpty) {
          ok = await inv.addVariants(existing.id, req.variantsJson);
        }
      }
    } else {
      ok = await inv.createProduct(
        name: _name.text.trim(),
        description: description,
        sku: _sku.text.trim(),
        costPrice: req.costPrice,
        sellingPrice: req.sellingPrice,
        quantity: withVariants ? 0 : req.quantity,
        minStock: req.minStock,
        category: category,
        categoryId: _categoryId,
        brandId: _brandId,
        unit: req.unit,
        unitFactor: req.unitFactor,
        status: _active ? 'active' : 'inactive',
        barcode: withVariants ? null : barcode,
        priceTier: req.priceTier,
        taxPercent: vat,
        measure: req.measure.wire,
        otherPrice: req.otherPrice,
        units: req.unitsJson,
        variants: withVariants ? req.variantsJson : const <Map<String, dynamic>>[],
        isService: _isService,
        durationMinutes: _isService ? duration : null,
        rebookAfterWeeks: _isService ? rebookWeeks : null,
        commissionPercent: _isService ? commission : null,
        commissionFixed: _isService ? commissionFixed : null,
        packageSessions: _isService && _isPackage ? packageSessions : null,
        packageServiceId: _isService && _isPackage ? _packageServiceId : null,
        packageValidDays: _isService && _isPackage ? packageDays : null,
        staffIds: _isService ? _staffIds.toList() : null,
        priceOptions: _isService ? options : null,
      );
    }

    if (!mounted) return;
    setState(() => _saving = false);
    if (ok) {
      ThemeConstants.showSuccessSnackBar(context, loc.translate('saved'));
      Navigator.pop(context);
    } else {
      // The server's own reason (a size that already exists, a SKU in use ...) when it gave one.
      final String message = inv.lastError ?? loc.translate('operation_failed');
      setState(() => _saveError = message);
      ThemeConstants.showErrorSnackBar(context, message);
    }
  }

  /// Editing: the prices that live on selling units rather than on the product -- the product's own unit at the
  /// other level, and (for goods by weight or volume) the kg / litre unit the price is quoted in.
  Future<void> _saveOtherPrices(InventoryProvider inv, InvProduct product, InvCapabilities caps, ProductRequest req) async {
    if (caps.isDepot) return;
    final List<InvProductUnit> units = await inv.fetchUnits(product.id);
    final InvProductUnit? base = units.where((InvProductUnit u) => u.isBase).firstOrNull;
    final bool wholesaleLevel = req.priceTier == 'wholesale';
    final InvPriceTier ownTier = wholesaleLevel ? InvPriceTier.wholesale : InvPriceTier.retail;

    if (_measure != ProductMeasure.count) {
      final InvProductUnit? big = units.where((InvProductUnit u) => !u.isBase && u.factor == _measure.bigFactor).firstOrNull;
      if (big != null && parseAmount(_price.text) > 0) {
        await inv.setUnitPrice(product.id, big.id, tier: ownTier, price: parseAmount(_price.text), reason: 'Edited');
      }
    }
    final double? other = optionalAmount(_otherPrice.text);
    if (base != null && other != null) {
      await inv.setUnitPrice(
        product.id,
        base.id,
        tier: wholesaleLevel ? InvPriceTier.retail : InvPriceTier.wholesale,
        price: req.otherPrice ?? other,
        reason: 'Edited',
      );
    }
  }

  Future<void> _onDelete() async {
    final LocalizationService loc = LocalizationService.instance;
    final InvProduct? p = widget.product;
    if (p == null) {
      // Nothing to delete yet in add mode.
      return;
    }

    final bool? confirmed = await showDialog<bool>(
      context: context,
      builder: (BuildContext ctx) => AlertDialog(
        backgroundColor: ThemeConstants.primaryBlue,
        shape:
            RoundedRectangleBorder(borderRadius: BorderRadius.circular(16.r)),
        title: Text(loc.translate('delete'), style: ThemeConstants.headingStyle),
        content: Text(p.name, style: ThemeConstants.bodyStyle),
        actions: <Widget>[
          TextButton(
            onPressed: () => Navigator.pop(ctx, false),
            child: Text(loc.translate('cancel')),
          ),
          TextButton(
            onPressed: () => Navigator.pop(ctx, true),
            child: Text(loc.translate('delete')),
          ),
        ],
      ),
    );
    if (confirmed != true || !mounted) return;

    setState(() => _saving = true);
    final String? err = await context.read<InventoryProvider>().deleteProduct(p.id);
    if (!mounted) return;
    setState(() => _saving = false);
    if (err == null) {
      ThemeConstants.showSuccessSnackBar(context, loc.translate('deleted'));
      Navigator.pop(context);
    } else if (err.toLowerCase().contains('sales history')) {
      final archive = await showDialog<bool>(
        context: context,
        builder: (dCtx) => AlertDialog(
          backgroundColor: ThemeConstants.primaryBlue,
          title: Text(LocalizationService.instance.translate('inv_cannot_delete'),
              style: ThemeConstants.bodyStyle
                  .copyWith(fontWeight: FontWeight.bold)),
          content: Text(
            '${LocalizationService.instance.translateWith('inv_has_sales_history', <Object?>[p.name])}\n\n'
            '${LocalizationService.instance.translate('inv_archive_instead')}',
            style: ThemeConstants.captionStyle,
          ),
          actions: [
            TextButton(
              onPressed: () => Navigator.pop(dCtx, false),
              child: Text(LocalizationService.instance.translate('cancel_2'),
                  style: const TextStyle(color: Colors.white70)),
            ),
            ElevatedButton(
              style: ElevatedButton.styleFrom(
                  backgroundColor: Colors.orange),
              onPressed: () => Navigator.pop(dCtx, true),
              child: Text(LocalizationService.instance.translate('inv_archive')),
            ),
          ],
        ),
      );
      if (archive == true && mounted) {
        final err2 = await context
            .read<InventoryProvider>()
            .deleteProduct(p.id, force: true);
        if (mounted) {
          if (err2 == null) {
            ThemeConstants.showSuccessSnackBar(
                context, LocalizationService.instance.translate('inv_product_archived'));
            Navigator.pop(context);
          } else {
            ThemeConstants.showErrorSnackBar(context, err2);
          }
        }
      }
    } else {
      ThemeConstants.showErrorSnackBar(context, err);
    }
  }
}

