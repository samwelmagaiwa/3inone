class AddEditProductScreen extends StatefulWidget {
  const AddEditProductScreen({super.key, this.product});
  /// null => add mode, otherwise edit this existing product.
  final InvProduct? product;

  @override
  State<AddEditProductScreen> createState() => _AddEditProductScreenState();
}

class _AddEditProductScreenState extends State<AddEditProductScreen> {
  // Basic controllers
  final TextEditingController _name = TextEditingController();
  final TextEditingController _sku = TextEditingController();
  final TextEditingController _category = TextEditingController();
  final TextEditingController _cost = TextEditingController();
  final TextEditingController _price = TextEditingController();
  final TextEditingController _qty = TextEditingController();
  final TextEditingController _minStock = TextEditingController(text: '0');
  final TextEditingController _barcode = TextEditingController();
  final TextEditingController _createdBy = TextEditingController();
  final TextEditingController _description = TextEditingController();

  String _unit = 'crate';
  // How many of `_unit` the cost/selling price below cover, e.g. "5" for "per 5 KG".
  final TextEditingController _unitFactor = TextEditingController(text: '1');
  bool _active = true;
  bool _isWholesale = true; // ON = wholesale (default)
  int? _categoryId;
  int? _brandId;
  bool _saving = false;

  // What kind of goods (counted, by weight, by volume); only a new product chooses it.
  ProductMeasure _measure = ProductMeasure.count;
  // Extra ways to sell it (carton, pack ...) being typed, and sizes / colours being typed.
  final List<UnitDraft> _unitDrafts = <UnitDraft>[];
  final List<VariantDraft> _variantDrafts = <VariantDraft>[];
  bool _hasVariants = false;
  // The product's own unit's price at the OTHER level (retail <-> wholesale), optional.
  final TextEditingController _otherPrice = TextEditingController();
  // This product's VAT rate; empty = the business's default.
  final TextEditingController _vat = TextEditingController();
  // Stock is typed in this unit: 1 = the base unit (g, ml, pcs), 1000 = kg / litre. Always whole numbers.
  int _stockUnitFactor = 1;
  // Once the user has picked a unit themselves we stop choosing one for them.
  bool _unitTouched = false;
  // The other sizes / colours of this product (edit mode).
  List<InvProduct> _family = <InvProduct>[];
  final TextEditingController _variantLabel = TextEditingController();
  String? _saveError;

  // Editing goods by weight or volume: the prices on screen are per kg / litre (they are stored per gram /
  // millilitre). Done once, as soon as the business's settings say this is not a depot.
  bool _editPricesConverted = false;

  bool _isSkuAutoGenerated = true;
  String _lastGeneratedSku = '';

  // Barcode mirrors SKU until the user manually types something different.
  bool _isBarcodeAutoGenerated = true;

  @override
  void didChangeDependencies() {
    super.didChangeDependencies();
    final InvProduct? p = widget.product;
    if (p == null || _editPricesConverted) return;
    // The settings may arrive after the page opens, so this waits for them instead of guessing at initState.
    final InvCapabilities caps = Provider.of<InventoryProvider>(context).capabilities;
    if (!caps.isDepot && _measure != ProductMeasure.count) {
      _editPricesConverted = true;
      // By weight or volume the price is typed per kg / litre, the stock in grams / millilitres.
      _cost.text = formatAmount(p.costPrice * _measure.bigFactor);
      _price.text = formatAmount(p.sellingPrice * _measure.bigFactor);
    }
  }

  @override
  void initState() {
    super.initState();
    final InvProduct? p = widget.product;
    final InvCapabilities caps = context.read<InventoryProvider>().capabilities;
    if (p == null) {
      _generateSku();
      // A depot starts on crates; everyone else on single pieces.
      if (!caps.isDepot) {
        _unit = 'pcs';
        _isWholesale = caps.saleTier == 'wholesale';
      }
    } else {
      _isSkuAutoGenerated = false;
      _name.text = p.name;
      _sku.text = p.sku;
      _description.text = p.description ?? '';
      _category.text = p.categoryName ?? p.category;
      _cost.text = formatAmount(p.costPrice);
      _price.text = formatAmount(p.sellingPrice);
      _qty.text = p.quantity.toString();
      _minStock.text = p.minStock.toString();
      _barcode.text = p.barcode;
      _unit = p.unit;
      _unitFactor.text = p.unitFactor.toString();
      _active = p.status == 'active';
      _categoryId = p.categoryId;
      _brandId = p.brandId;
      _isWholesale = p.isWholesale;
      _measure = ProductMeasure.parse(p.measure);
      _vat.text = p.taxPercent == null ? '' : _plainNumber(p.taxPercent!);
      _hasVariants = p.isVariant;
      _variantLabel.text = p.variantLabel ?? '';
    }
    _name.addListener(_onNameChanged);
    _sku.addListener(_onSkuChanged);
    _barcode.addListener(_onBarcodeChanged);
    _cost.addListener(_rebuild);
    _price.addListener(_rebuild);
    _unitFactor.addListener(_rebuild);
    _qty.addListener(_rebuild);

    WidgetsBinding.instance.addPostFrameCallback((_) {
      final InventoryProvider inv = context.read<InventoryProvider>()
        ..fetchCategories()
        ..fetchBrands()
        ..fetchCapabilities();
      final InvProduct? existing = widget.product;
      if (existing != null && existing.familyId != null) {
        inv.fetchFamily(existing.familyId!).then((List<InvProduct> family) {
          if (mounted) setState(() => _family = family);
        });
      }
      final authUser = context.read<AuthProvider>().user;
      if (authUser != null && _createdBy.text.isEmpty) {
        _createdBy.text = authUser.name.isNotEmpty ? authUser.name : authUser.email;
      }
    });
  }

  void _onNameChanged() {
    if (_isSkuAutoGenerated && widget.product == null) {
      _generateSku(_name.text);
    }
  }

  void _onSkuChanged() {
    if (_sku.text != _lastGeneratedSku) {
      _isSkuAutoGenerated = false;
    }
    // Keep barcode in sync with SKU as long as the user hasn't customized it.
    if (_isBarcodeAutoGenerated) {
      _barcode.value = TextEditingValue(
        text: _sku.text,
        selection: TextSelection.collapsed(offset: _sku.text.length),
      );
    }
    if (mounted) setState(() {});
  }

  void _onBarcodeChanged() {
    // If the user typed something different from the current SKU, stop auto-sync.
    if (_barcode.text != _sku.text) {
      _isBarcodeAutoGenerated = false;
    }
    if (mounted) setState(() {});
  }

  void _generateSku([String? inputName]) {
    String prefix = 'SKU';
    final name = (inputName ?? _name.text).trim();
    if (name.isNotEmpty) {
      final parts = name.split(RegExp(r'\s+'));
      if (parts.length >= 2) {
        String p1 = parts[0].replaceAll(RegExp(r'[^a-zA-Z]'), '').toUpperCase();
        String p2 = parts[1].replaceAll(RegExp(r'[^a-zA-Z]'), '').toUpperCase();
        p1 = p1.length >= 3 ? p1.substring(0, 3) : (p1.isEmpty ? 'SKU' : p1.padRight(3, 'X'));
        p2 = p2.length >= 3 ? p2.substring(0, 3) : (p2.isEmpty ? '' : p2.padRight(3, 'X'));
        prefix = p2.isEmpty ? p1 : '$p1-$p2';
      } else {
        String p1 = parts[0].replaceAll(RegExp(r'[^a-zA-Z]'), '').toUpperCase();
        p1 = p1.length >= 3 ? p1.substring(0, 3) : (p1.isEmpty ? 'SKU' : p1.padRight(3, 'X'));
        prefix = p1;
      }
    }
    final int randomNum = 1000 + math.Random().nextInt(9000);
    _lastGeneratedSku = '$prefix-$randomNum';
    _isSkuAutoGenerated = true; // temporarily set true to bypass listener
    
    // update controller without triggering the focus change or caret reset if possible, 
    // but text update resets caret. To prevent caret jump when typing _name, 
    // we only update _sku value if it's not focused.
    _sku.value = TextEditingValue(
      text: _lastGeneratedSku,
      selection: TextSelection.collapsed(offset: _lastGeneratedSku.length),
    );
    // Mirror to barcode if user hasn't customized it.
    if (_isBarcodeAutoGenerated) {
      _barcode.value = TextEditingValue(
        text: _lastGeneratedSku,
        selection: TextSelection.collapsed(offset: _lastGeneratedSku.length),
      );
    }
  }

  void _rebuild() {
    if (mounted) setState(() {});
  }

  @override
  void dispose() {
    _name.removeListener(_onNameChanged);
    _sku.removeListener(_onSkuChanged);
    _barcode.removeListener(_onBarcodeChanged);
    _cost.removeListener(_rebuild);
    _price.removeListener(_rebuild);
    _qty.removeListener(_rebuild);
    _unitFactor.removeListener(_rebuild);
    _name.dispose();
    _sku.dispose();
    _category.dispose();
    _cost.dispose();
    _price.dispose();
    _qty.dispose();
    _minStock.dispose();
    _barcode.dispose();
    _unitFactor.dispose();
    _createdBy.dispose();
    _description.dispose();
    _otherPrice.dispose();
    _vat.dispose();
    _variantLabel.dispose();
    for (final UnitDraft d in _unitDrafts) {
      d.dispose();
    }
    for (final VariantDraft d in _variantDrafts) {
      d.dispose();
    }
    super.dispose();
  }

  /// 18 -> "18", 16.5 -> "16.5" (no trailing ".0").
  String _plainNumber(double v) => v % 1 == 0 ? v.toInt().toString() : v.toString();

